-- Banco de dados do Meclaz Pets
-- Execute este arquivo no Query Tool do banco meclaz_pets.
-- Ordem: animais, usuarios e solicitacoes.

CREATE TABLE IF NOT EXISTS animais (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    especie VARCHAR(50) NOT NULL,
    idade_em_meses INTEGER NOT NULL CHECK (idade_em_meses >= 0),
    disponivel BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash TEXT NOT NULL,
    tipo VARCHAR(20) NOT NULL DEFAULT 'admin',
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS solicitacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id INTEGER NOT NULL REFERENCES animais(id),
    nome_interessado VARCHAR(100) NOT NULL,
    contato VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pendente'
);
